"""Intermediate files: what the arms leave behind that nothing downstream reads.

The rMLST arm tidies up after itself (it removes its work folder and
diagnostics unless ``--keep-temp``). For the 16S and AMR arms this module does
it; on a run of 100+ samples their working files are most of the tree:

* ``16s/alignment/`` - the stage that measures identity and coverage aligns
  every read to the called genera's MIMt sequences. Its BAM, the uncompressed
  SAM of primary alignments, the per-genus SAM, the reference subsets and the
  per-genus BLAST databases exist only to produce the numbers already written
  into ``marker16s_calls.csv``.
* ``amr/kma.aln`` and ``amr/kma.mat.gz`` - KMA's per-template alignments and
  per-position base counts. ``amr_hits.csv`` holds every number the report
  uses; these two are for looking at one disputed allele by hand.

What stays, because ``finalise`` / ``amr-report`` read it or it is small and
worth having: every ``*_calls.csv``, the manifests and logs,
``16s/quant/`` (``run_info.json`` is the RPM denominator; ``abundance.tsv``
lets ``--arms 16s`` reuse the quantification), each genus's
``consensus.fasta`` / ``blast.tsv`` / ``depth.tsv``, and ``kma.res``,
``kma.mapstat`` and ``kma.fsa``.

Everything removed here is regenerated by re-running that arm for that sample
with ``--keep-temp``.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from pathlib import Path

# Per arm, glob patterns relative to the sample folder.
INTERMEDIATES: dict[str, tuple[str, ...]] = {
    "16s": (
        "16s/alignment/alignment.sam",          # normally already gone; left by a crash
        "16s/alignment/alignment.bam",
        "16s/alignment/alignment.bam.bai",
        "16s/alignment/primary.sam",
        "16s/alignment/references.fasta",
        "16s/alignment/*/references.fasta",
        "16s/alignment/*/top_reference.sam",
        "16s/alignment/*/blastdb",
    ),
    "amr": (
        "amr/kma.aln",
        "amr/kma.mat.gz",
    ),
}

# The rMLST arm's full-reference BLAST database, shared by every sample of a
# run. Only the sample jobs use it, and `bridge run` rebuilds it when it is
# missing, so it can go once the run is finished - but not while jobs run.
BLAST_CACHE = ".bridge_blastdb"


def size_of(path: Path) -> int:
    path = Path(path)
    if path.is_symlink() or path.is_file():
        return path.lstat().st_size
    if path.is_dir():
        return sum(item.lstat().st_size for item in path.rglob("*")
                   if item.is_file() or item.is_symlink())
    return 0


def intermediate_paths(sample_dir: Path, arms: tuple[str, ...] = tuple(INTERMEDIATES)
                       ) -> list[Path]:
    sample_dir = Path(sample_dir)
    found: list[Path] = []
    for arm in arms:
        for pattern in INTERMEDIATES.get(arm, ()):
            found.extend(sorted(sample_dir.glob(pattern)))
    return found


def remove(path: Path) -> None:
    path = Path(path)
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def remove_intermediates(sample_dir: Path, arms: tuple[str, ...]) -> int:
    """Delete one sample's intermediates for ``arms``; returns the bytes freed."""
    freed = 0
    for path in intermediate_paths(sample_dir, arms):
        freed += size_of(path)
        remove(path)
    return freed


@dataclass
class CleanReport:
    files: dict[str, int] = field(default_factory=dict)      # category -> paths
    sizes: dict[str, int] = field(default_factory=dict)      # category -> bytes
    samples: int = 0
    skipped: list[str] = field(default_factory=list)          # job still queued/running
    removed: bool = False
    blast_cache: Path | None = None
    blast_cache_size: int = 0
    blast_cache_note: str = ""

    @property
    def total(self) -> int:
        return sum(self.sizes.values()) + (self.blast_cache_size if self.blast_cache else 0)


def _category(sample_dir: Path, path: Path) -> str:
    """``16s/alignment/*/blastdb`` style label for a path, for the summary table."""
    relative = path.relative_to(sample_dir).parts
    if len(relative) >= 4 and relative[:2] == ("16s", "alignment"):
        return "16s/alignment/<genus>/" + relative[-1]
    return "/".join(relative)


def run_jobs_active(out_root: Path) -> dict[str, str]:
    """Samples of this run whose job PBS still holds (from ``oe/.jobids``): {sample: job}."""
    from .pbs import active_jobs
    jobids_dir = Path(out_root) / "oe" / ".jobids"
    if not jobids_dir.is_dir():
        return {}
    running = active_jobs()
    held = {}
    for jid_file in jobids_dir.iterdir():
        job = jid_file.read_text().strip() if jid_file.is_file() else ""
        if job and job in running:
            held[jid_file.name] = job
    return held


def clean_run(out_root: Path, *, apply: bool = False, blast_cache: bool = False) -> CleanReport:
    """Measure (and with ``apply``, delete) the intermediates of a results tree.

    A sample whose job is still queued or running is left alone: its arms may
    be writing (or about to read) exactly these files.
    """
    from .finalise import sample_dirs
    out_root = Path(out_root).resolve()
    if not out_root.is_dir():
        raise FileNotFoundError(f"no such results directory: {out_root}")
    report = CleanReport(removed=apply)
    held = run_jobs_active(out_root)
    report.skipped = sorted(held)
    for sample_dir in sample_dirs(out_root):
        if sample_dir.name in held:
            continue
        paths = intermediate_paths(sample_dir)
        if paths:
            report.samples += 1
        for path in paths:
            label = _category(sample_dir, path)
            report.files[label] = report.files.get(label, 0) + 1
            report.sizes[label] = report.sizes.get(label, 0) + size_of(path)
            if apply:
                remove(path)

    cache = out_root / BLAST_CACHE
    if cache.is_dir():
        report.blast_cache_size = size_of(cache)
        if not blast_cache:
            report.blast_cache_note = "kept (add --blast-cache to remove it too)"
        else:
            if held:
                report.blast_cache_note = "kept: sample jobs are still queued or running"
            else:
                report.blast_cache = cache
                if apply:
                    remove(cache)
    return report


def human(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return f"{size} B"


def describe(report: CleanReport, out_root: Path) -> str:
    verb = "Removed" if report.removed else "Would remove"
    lines = [f"Results    : {out_root}",
             f"Samples    : {report.samples} with intermediates"]
    if report.skipped:
        lines.append(f"Left alone : {len(report.skipped)} sample(s) whose job is still queued "
                     f"or running: {', '.join(report.skipped)}")
    lines.append("")
    if report.sizes:
        width = max(len(label) for label in report.sizes)
        for label in sorted(report.sizes, key=report.sizes.get, reverse=True):
            lines.append(f"  {label:<{width}}  {report.files[label]:>5} item(s)  "
                         f"{human(report.sizes[label]):>10}")
    else:
        lines.append("  no per-sample intermediates found")
    if report.blast_cache_size:
        status = (f"{'removed' if report.removed else 'would be removed'}"
                  if report.blast_cache else report.blast_cache_note)
        lines.append(f"  {BLAST_CACHE}/ (shared by the run)  {human(report.blast_cache_size)}"
                     f"  - {status}")
    lines += ["", f"{verb:<11}: {human(report.total)}"]
    if not report.removed:
        lines.append("Nothing was deleted. Add --apply to delete the files above.")
    lines.append("Kept: every *_calls.csv, manifests and logs, 16s/quant/, each genus's "
                 "consensus.fasta and blast.tsv, kma.res/.mapstat/.fsa - all that "
                 "finalise and amr-report read.")
    return "\n".join(lines)
